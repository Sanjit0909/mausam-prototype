export function localizePersonaCardText(text: string, locale: string): string {
  if (!text || locale !== "hi") return text;
  const exact = EXACT[text.trim()];
  if (exact) return exact;
  let out = text;
  for (const [re, hi] of PHRASES) {
    out = out.replace(re, hi);
  }
  return out;
}
